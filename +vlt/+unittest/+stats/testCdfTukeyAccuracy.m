    methods (Test)

        function testKnownValues95(testCase)
            for i = 1:size(testCase.Q95,1)
                row = testCase.Q95(i,:);
                p = vlt.stats.cdfTukey(row{1}, row{2}, row{3});
                testCase.verifyEqual(p, row{4}, 'AbsTol', testCase.AbsTol, ...
                    sprintf('Failed for q=%.6f, k=%d, v=%g', row{1}, row{2}, row{3}));
            end
        end

        function testOtherProbabilityLevels(testCase)
            for i = 1:size(testCase.QOther,1)
                row = testCase.QOther(i,:);
                p = vlt.stats.cdfTukey(row{1}, row{2}, row{3});
                testCase.verifyEqual(p, row{4}, 'AbsTol', testCase.AbsTol, ...
                    sprintf('Failed for q=%.6f, k=%d, v=%g, p=%.2f', ...
                        row{1}, row{2}, row{3}, row{4}));
            end
        end

        function testLargeVDoesNotSaturate(testCase)
            % The signature of issue #141: a probability coming back as
            % exactly 1 where it should be about 0.95.
            for v = [60 120 240 1000]
                p = vlt.stats.cdfTukey(3.4, 3, v);
                testCase.verifyLessThan(p, 1, ...
                    sprintf('cdfTukey saturated at 1 for v=%g', v));
                testCase.verifyGreaterThan(p, 0, ...
                    sprintf('cdfTukey returned 0 for v=%g', v));
            end
        end

        function testNoOverflowAtLargeV(testCase)
            % 2*(v/2)^(v/2) overflows double near v=290, so the constant must
            % be accumulated in log space. Issue #141.
            for v = [290 400 1000 10000]
                p = vlt.stats.cdfTukey(3.4, 3, v);
                testCase.verifyTrue(isfinite(p), ...
                    sprintf('cdfTukey returned a non-finite value for v=%g', v));
                testCase.verifyGreaterThanOrEqual(p, 0);
                testCase.verifyLessThanOrEqual(p, 1);
            end
        end

        function testInfiniteDfBranch(testCase)
            % v > 25000 takes the s=1 limit rather than integrating; it should
            % agree closely with a large but finite v.
            pBig   = vlt.stats.cdfTukey(3.3147, 3, 20000);
            pLimit = vlt.stats.cdfTukey(3.3147, 3, 30000);
            testCase.verifyEqual(pLimit, pBig, 'AbsTol', 1e-3, ...
                'Infinite-df branch disagrees with the finite-v integral.');
        end

        function testMonotoneInQ(testCase)
            % A cdf must be non-decreasing in q.
            qs = 1:0.5:8;
            p  = arrayfun(@(x) vlt.stats.cdfTukey(x, 5, 30), qs);
            testCase.verifyGreaterThanOrEqual(min(diff(p)), -1e-10, ...
                'cdfTukey is not monotone non-decreasing in q.');
        end

        function testMonotoneInV(testCase)
            % For fixed q and k, more degrees of freedom means more mass below q.
            vs = [5 10 20 30 60 120 240];
            p  = arrayfun(@(x) vlt.stats.cdfTukey(4, 5, x), vs);
            testCase.verifyGreaterThanOrEqual(min(diff(p)), -1e-10, ...
                'cdfTukey is not monotone non-decreasing in v.');
        end

        function testKequals2MatchesTcdf(testCase)
            % The k=2 branch is exact; check it against the t-distribution.
            for v = [10 60 240]
                q = 3.0;
                expected = tcdf(q/sqrt(2), v) - tcdf(-q/sqrt(2), v);
                testCase.verifyEqual(vlt.stats.cdfTukey(q, 2, v), expected, ...
                    'AbsTol', 1e-12);
            end
        end

    end % methods (Test)

